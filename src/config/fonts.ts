export type FontStyle = 'normal' | 'italic';

export interface FontVariant {
  /** A package import or a path relative to the project root. */
  src: string;
  style: FontStyle;
  unicodeRange: string;
}

export interface FontFamilyConfig {
  name: string;
  cssVariable: `--font-${string}`;
  variants: FontVariant[];
}

const pkg = (name: string, file: string) => `@fontsource-variable/${name}/files/${file}`;

/**
 * Glyph subsets for the foreign-script words in each language's pages, generated by
 * scripts/build-font-assets.py: one with the characters the copy uses (the language switcher, «бомбардир»)
 * and, where the guides use more (the Russian glossary's Armenian column), one with only those. Each declares
 * exactly its characters as its unicode-range, so a page downloads only the subsets it draws from.
 */
export const FOREIGN_SUBSETS: Record<'en' | 'ru' | 'hy', ReadonlyArray<{ src: string; script: string; unicodeRange: string }>> = foreignSubsets;

const foreign = (lang: keyof typeof FOREIGN_SUBSETS): FontVariant[] =>
  FOREIGN_SUBSETS[lang].map(({ src, unicodeRange }) => ({ src, style: 'normal', unicodeRange }));

